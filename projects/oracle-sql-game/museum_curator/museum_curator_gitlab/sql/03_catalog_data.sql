-- Двадцать экспонатов, которые игрок может купить.
-- У каждого свой тип, цена, привлекательность и тема.
-- Если тема пустая, экспонат считается нейтральным: он нравится
-- всем категориям посетителей одинаково.

DECLARE
  v_hist NUMBER;
  v_art  NUMBER;
  v_sci  NUMBER;

  PROCEDURE add_ex(p_theme NUMBER, p_name VARCHAR2, p_type VARCHAR2,
                   p_stars NUMBER, p_price NUMBER, p_attr NUMBER, p_desc VARCHAR2) IS
  BEGIN
    INSERT INTO exhibit_catalog (catalog_exhibit_id, theme_id, exhibit_name,
                                    exhibit_type, star_rating, price, attractiveness, description)
    VALUES (seq_exhibit_catalog.NEXTVAL, p_theme, p_name, p_type, p_stars, p_price, p_attr, p_desc);
  END;
BEGIN
  SELECT theme_id INTO v_hist FROM themes WHERE theme_name = 'История';
  SELECT theme_id INTO v_art  FROM themes WHERE theme_name = 'Искусство';
  SELECT theme_id INTO v_sci  FROM themes WHERE theme_name = 'Наука';

  -- Исторические, 7 штук
  add_ex(v_hist,'Скифская золотая пектораль','Артефакт',  5, 4200, 260, 'Нагрудное украшение IV века до н.э.');
  add_ex(v_hist,'Рыцарский доспех','Артефакт',            4, 2600, 170, 'Полный турнирный доспех XV века');
  add_ex(v_hist,'Берестяная грамота','Артефакт',          3, 900,   70, 'Новгородское письмо XII века');
  add_ex(v_hist,'Бюст римского сенатора','Скульптура',    4, 2400, 160, 'Мраморный портрет эпохи Империи');
  add_ex(v_hist,'Карта Великих открытий','Картина',       3, 1100,   85, 'Гравированная карта XVI века');
  add_ex(v_hist,'Египетский саркофаг','Артефакт',         5, 5000, 300, 'Расписной саркофаг Нового царства');
  add_ex(v_hist,'Монетный клад','Артефакт',               3, 1000,   80, 'Кувшин с серебряными монетами');

  -- Искусство, 7 штук
  add_ex(v_art,'Портрет незнакомки','Картина',            4, 3000, 190, 'Парадный портрет XIX века');
  add_ex(v_art,'Пейзаж с мельницей','Картина',            3, 1200,   90, 'Голландская школа, масло');
  add_ex(v_art,'Мраморная Венера','Скульптура',           5, 4800, 290, 'Копия античного оригинала');
  add_ex(v_art,'Авангардная композиция','Картина',        4, 2800, 180, 'Беспредметная живопись начала XX века');
  add_ex(v_art,'Бронзовый танцор','Скульптура',           4, 2500, 165, 'Динамичная бронза в стиле модерн');
  add_ex(v_art,'Натюрморт с фруктами','Картина',          3, 950,    75, 'Учебный натюрморт малых голландцев');
  add_ex(v_art,'Витраж «Розовое окно»','Артефакт',        5, 4500, 275, 'Фрагмент готического витража');

  -- Наука, 5 штук
  add_ex(v_sci,'Модель Солнечной системы','Артефакт',     4, 2700, 175, 'Механический теллурий XVIII века');
  add_ex(v_sci,'Скелет тираннозавра','Артефакт',          5, 5200, 310, 'Смонтированный слепок скелета');
  add_ex(v_sci,'Старинный микроскоп','Артефакт',          3, 1050,   82, 'Латунный микроскоп XIX века');
  add_ex(v_sci,'Метеорит Сихотэ-Алинь','Артефакт',        4, 2900, 185, 'Железный метеорит с регмаглиптами');
  add_ex(v_sci,'Чертёж летательной машины','Картина',     3, 1150,   88, 'Инженерный эскиз эпохи Возрождения');

  -- Один без темы, он нравится всем понемногу
  add_ex(NULL, 'Мозаичный пол','Артефакт',                3, 1300,   95, 'Нейтральный экспонат, подходит любому залу');

  COMMIT;
END;
